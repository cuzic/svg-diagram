import {checkInsight} from './wireframe-insight.ts';
import type {Wf, WfChildren, WfNode, WfNodeOf, WfType} from './types/wireframe-nodes.ts';

const mk = <T extends WfType>(t: T, o: object = {}): WfNodeOf<T> => ({t, ...o}) as WfNodeOf<T>;
const kids = (children: WfChildren): WfNode[] => ([children] as unknown[]).flat(Infinity).filter(Boolean) as WfNode[];

export const col: Wf['col'] = (c, o) => mk('col', {...o, children: kids(c)});
export const row: Wf['row'] = (c, o) => mk('row', {...o, children: kids(c)});
export const card: Wf['card'] = (c, o) => mk('card', {...o, children: kids(c)});
export const spacer: Wf['spacer'] = (h = 8, o) => mk('spacer', {h, ...o});
export const text: Wf['text'] = (text, o) => mk('text', {...o, text});
export const btn: Wf['btn'] = (label, o) => mk('btn', {...o, label});
export const input: Wf['input'] = (label, o) => mk('input', {...o, label});
export const select: Wf['select'] = (label, o) => mk('select', {...o, label});
export const chip: Wf['chip'] = (label, o) => mk('chip', {...o, label});
export const tabs: Wf['tabs'] = (labels, o) => mk('tabs', {...o, labels});
export const appbar: Wf['appbar'] = (title, o) => mk('appbar', {...o, title});
export const seek: Wf['seek'] = (o) => mk('seek', o);
export const kv: Wf['kv'] = (pairs, o) => mk('kv', {...o, pairs});
export const stat: Wf['stat'] = (value, label, o) => mk('stat', {...o, value: String(value), label});
export const list: Wf['list'] = (items, o) => mk('list', {...o, items});
export const table: Wf['table'] = (columns, rows, o) => mk('table', {...o, columns, rows});
export const alert: Wf['alert'] = (text, o) => mk('alert', {...o, text});
export const map: Wf['map'] = (o) => mk('map', o);
export const video: Wf['video'] = (o) => mk('video', o);
export const heat: Wf['heat'] = (o) => mk('heat', o);
export const pointcloud: Wf['pointcloud'] = (o) => mk('pointcloud', o);
export const chart: Wf['chart'] = (o) => mk('chart', o);
export const image: Wf['image'] = (label, o) => mk('image', {...o, label});
export const dialog: Wf['dialog'] = (title, o) => mk('dialog', {...o, title});
export const toast: Wf['toast'] = (text, o) => mk('toast', {...o, text});
export const fusion: Wf['fusion'] = (o) => mk('fusion', o);
export const compare: Wf['compare'] = (o) => mk('compare', o);
export const region: Wf['region'] = (label, o) => mk('region', {...o, label});
export const robot: Wf['robot'] = (o) => mk('robot', o);
export const battery: Wf['battery'] = (level, o) => mk('battery', {...o, level});
export const signal: Wf['signal'] = (level, o) => mk('signal', {...o, level});
export const insight: Wf['insight'] = (o) => { checkInsight(o); return mk('insight', o); };
export const breadcrumb: Wf['breadcrumb'] = (items, o) => mk('breadcrumb', {...o, items});
export const toggle: Wf['toggle'] = (label, o) => mk('toggle', {...o, label});
export const checkbox: Wf['checkbox'] = (label, o) => mk('checkbox', {...o, label});
export const radio: Wf['radio'] = (label, o) => mk('radio', {...o, label});
export const slider: Wf['slider'] = (label, o) => mk('slider', {...o, label});

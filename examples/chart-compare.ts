import {compare, diagram} from 'svg-diagram';

// 比較表: 比較軸ごとに、3 つの案を ○△× と理由で評価する。マークと理由の間は破線で区切る。
export default function define() {
  return diagram({theme: 'blue', title: '導入案の比較', sourceLine: '出典: 説明用の例'}).add(
    compare(
      ['コスト', '導入期間', '拡張性'],
      ['案A', '案B', '案C'],
      [
        [['○', '既存設備を流用できる'], ['△', '追加ライセンスが必要'], ['×', '初期投資が大きい']],
        [['△', '設定に時間がかかる'], ['○', 'すぐに導入できる'], ['×', '個別開発が必要']],
        [['×', 'カスタマイズ不可'], ['△', '一部のみ変更可能'], ['○', '自由に拡張できる']],
      ],
      {corner: '比較軸'},
    ),
  );
}

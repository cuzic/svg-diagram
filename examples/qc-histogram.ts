// `lsl` / `usl` で規格の下限・上限（外の区間は赤）、平均線は既定で付く。`normal: true` で正規分布の曲線を重ねる。
const lengths = [
  9.82, 9.91, 9.95, 9.97, 9.99, 10.0, 10.0, 10.01, 10.02, 10.02, 10.03, 10.04, 10.05, 10.05, 10.06, 10.07, 10.08,
  10.08, 10.1, 10.11, 10.12, 10.13, 10.15, 10.16, 10.18, 10.2, 10.22, 10.25, 10.27, 10.3, 10.34, 10.38, 10.44, 10.52,
  9.88, 9.93, 9.96, 9.98, 10.0, 10.01, 10.03, 10.04, 10.06, 10.09, 10.1, 10.12, 10.14, 10.17, 10.21, 10.29,
];
export default function define() {
  return diagram({theme: 'blue', title: '部品の長さの分布（ヒストグラム）', sourceLine: '出典: 説明用の例'}).add(
    histogram(lengths, {lsl: 9.8, usl: 10.4, normal: true, unit: '個', height: 300}),
  );
}

import {diagram, xbarR} from 'svg-diagram';

// 管理図（X̄-R 管理図）: 群ごとの測定値を渡すと、中心線と管理限界（3σ）を計算して、平均と範囲の 2 枚を出す。
// 管理限界の外は赤い ✕、中心線の同じ側に 7 点続く・7 点続けて上がる/下がる点は赤い ○ になる。
const groups = [
  [10.1, 10.0, 9.9, 10.2, 10.0], [10.0, 10.1, 10.0, 9.9, 10.1], [9.9, 10.0, 10.2, 10.1, 10.0], [10.2, 10.1, 10.0, 10.1, 10.3],
  [10.0, 9.9, 10.0, 10.1, 9.8], [10.1, 10.2, 10.1, 10.0, 10.2], [10.3, 10.2, 10.1, 10.4, 10.2], [10.0, 10.1, 9.9, 10.0, 10.1],
  [9.9, 10.0, 10.0, 9.8, 9.9], [10.1, 10.0, 10.2, 10.0, 10.1], [10.6, 10.5, 10.7, 10.4, 10.6], [10.0, 10.1, 10.0, 10.2, 9.9],
  [10.1, 9.9, 10.0, 10.1, 10.0], [10.0, 10.0, 10.1, 9.9, 10.2], [10.2, 10.0, 10.1, 10.1, 10.0],
];
export default function define() {
  return diagram({theme: 'blue', title: '軸径の X̄-R 管理図', sourceLine: '出典: 説明用の例'}).add(...xbarR(groups, {xLabel: '群の番号'}));
}

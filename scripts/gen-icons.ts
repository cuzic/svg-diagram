// Regenerates lib/icon-paths.ts: the path data of the few icons icon() offers, taken from the devDependencies
// @mdi/js (Material Design Icons, Pictogrammers; Apache-2.0) and @material-symbols/svg-400 (Google; Apache-2.0).
// Run: node scripts/gen-icons.ts. The icons are copied into the repo, so nothing here is a runtime dependency.
import fs from 'fs';
import {createRequire} from 'module';

const require = createRequire(import.meta.url);
const mdi: Record<string, string> = require('@mdi/js');
const msDir = require.resolve('@material-symbols/svg-400/package.json').replace(/package\.json$/, 'outlined/');

// name used in svg-diagram -> where it comes from. 'mdi': an @mdi/js export; 'ms': a Material Symbols (outlined, 400) file.
const PICKS: Record<string, ['mdi' | 'ms', string]> = {
  person: ['mdi', 'mdiAccount'],
  people: ['mdi', 'mdiAccountMultiple'],
  document: ['mdi', 'mdiFileDocumentOutline'],
  folder: ['mdi', 'mdiFolderOutline'],
  key: ['mdi', 'mdiKeyVariant'],
  lock: ['mdi', 'mdiLock'],
  bridge: ['mdi', 'mdiBridge'],
  fence: ['mdi', 'mdiFence'],
  stairs: ['mdi', 'mdiStairs'],
  warning: ['mdi', 'mdiAlert'],
  check: ['mdi', 'mdiCheck'],
  close: ['mdi', 'mdiClose'],
  idea: ['mdi', 'mdiLightbulbOnOutline'],
  search: ['mdi', 'mdiMagnify'],
  gear: ['mdi', 'mdiCog'],
  cloud: ['mdi', 'mdiCloud'],
  database: ['mdi', 'mdiDatabase'],
  mail: ['mdi', 'mdiEmailOutline'],
  shield: ['mdi', 'mdiShieldOutline'],
  flag: ['mdi', 'mdiFlag'],
  clock: ['mdi', 'mdiClockOutline'],
  link: ['mdi', 'mdiLink'],
  target: ['mdi', 'mdiTarget'],
  tool: ['ms', 'build'],
  tree: ['ms', 'account_tree'],
};

const lines: string[] = [];
for (const [name, [from, src]] of Object.entries(PICKS)) {
  let d: string, vb: string;
  if (from === 'mdi') {
    d = mdi[src];
    vb = '0 0 24';
  } else {
    const svg = fs.readFileSync(`${msDir}${src}.svg`, 'utf8');
    const paths = [...svg.matchAll(/<path d="([^"]+)"/g)];
    if (paths.length !== 1) throw new Error(`${src}: expected one <path>, found ${paths.length}`);
    d = paths[0][1];
    vb = (/viewBox="([^"]+)"/.exec(svg) as RegExpExecArray)[1].split(' ').slice(0, 3).join(' ');
  }
  if (!d) throw new Error(`${from}:${src} not found`);
  const [x, y, size] = vb.split(' ').map(Number);
  lines.push(`  ${name}: {from: '${from}', src: '${src}', vb: [${x}, ${y}, ${size}], d: '${d}'},`);
}

fs.writeFileSync(new URL('../lib/icon-paths.ts', import.meta.url), `// GENERATED by scripts/gen-icons.ts — do not edit. Path data copied from Material Design Icons (@mdi/js, Pictogrammers)
// and Material Symbols (Google), both Apache-2.0: see NOTICE. \`vb\` is the source viewBox as [minX, minY, size] (square).

export interface IconPath {
  from: 'mdi' | 'ms';
  src: string;
  vb: [number, number, number];
  d: string;
}

export const ICON_PATHS = {
${lines.join('\n')}
} as const satisfies Record<string, IconPath>;
`);

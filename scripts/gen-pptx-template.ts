#!/usr/bin/env node
// Writes lib/pptx/template.ts from the files under lib/pptx/template/: the package skeleton as a module, so the writer needs no file
// system (the edge entry runs in a Worker). test/pptx.test.ts fails when the two differ; run this after changing a template file.
//   node scripts/gen-pptx-template.ts
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIR = path.join(ROOT, 'lib/pptx/template');
const OUT = path.join(ROOT, 'lib/pptx/template.ts');

const walk = (dir: string, prefix = ''): string[] => fs.readdirSync(dir, {withFileTypes: true})
  .flatMap(e => e.isDirectory() ? walk(path.join(dir, e.name), prefix + e.name + '/') : [prefix + e.name]);

const names = walk(DIR).sort();
const body = names.map(n => `  {name: ${JSON.stringify(n)}, text: ${JSON.stringify(fs.readFileSync(path.join(DIR, n), 'utf8'))}},`).join('\n');
fs.writeFileSync(OUT, `// Generated by scripts/gen-pptx-template.ts from lib/pptx/template/: do not edit by hand.
/** The fixed files of the .pptx package (ADR 0027 D4), sorted by name. All are XML text. */
export const TEMPLATE: readonly {name: string; text: string}[] = [
${body}
];
`);
console.log(`wrote ${path.relative(ROOT, OUT)} (${names.length} files)`);
